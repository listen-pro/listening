// Builds css/remixicon.css with only the Remix Icon glyphs the app uses, and embeds that
// font in the stylesheet. Icons then draw together with the page's first paint instead of
// waiting for a separate 140 KB font download (5-10 s on a slow phone connection).
//
// Run it after adding, removing or renaming an icon class (ri-...) in the pages or scripts,
// for example a topic icon in js/topics.js:
//   cd tools/icons && npm install && npm run build
// Then bump CACHE_NAME in sw.js.
//
// Sources: remixicon.css and remixicon.woff2 in this folder are the full Remix Icon 3.5.0 set
// (license: fonts/Remixicon-LICENSE.txt). They are only read here, the pages never load them.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const OUT = 'css/remixicon.css';
// Files that may name icons. Every js/*.js is included so a new script is not missed.
const SOURCES = [
  'index.html',
  'login.html',
  'css/style.css',
  ...fs.readdirSync(path.join(ROOT, 'js')).filter(f => f.endsWith('.js')).map(f => 'js/' + f)
];
// Files whose link to the stylesheet gets the new ?v= hash, so browsers and the service
// worker fetch the new copy instead of an old one.
const REFERENCES = ['index.html', 'login.html', 'sw.js'];

// Class name -> code point, from the full stylesheet.
const glyphs = new Map();
const fullCss = fs.readFileSync(path.join(HERE, 'remixicon.css'), 'utf8');
for (const m of fullCss.matchAll(/\.(ri-[a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)";?\s*\}/gi)) {
  glyphs.set(m[1], parseInt(m[2], 16));
}

const used = new Set();
const unknown = new Set();
for (const rel of SOURCES) {
  const text = fs.readFileSync(path.join(ROOT, rel), 'utf8');
  for (const [name] of text.matchAll(/\bri-[a-z0-9]+(?:-[a-z0-9]+)*/g)) {
    (glyphs.has(name) ? used : unknown).add(name);
  }
}
if (!used.size) throw new Error('No icon classes found; check SOURCES.');

const names = [...used].sort();
const codePoints = [...new Set(names.map(n => glyphs.get(n)))];
const font = await subsetFont(
  fs.readFileSync(path.join(HERE, 'remixicon.woff2')),
  String.fromCodePoint(...codePoints),
  { targetFormat: 'woff2' }
);

const css = `/*
* Remix Icon v3.5.0, https://remixicon.com, Apache License 2.0 (fonts/Remixicon-LICENSE.txt)
*
* GENERATED by tools/icons/build.mjs. Do not edit by hand: add the icon class to the page or
* script, then run the build again. Only the ${names.length} icons the app uses are included, and the
* font is embedded so icons draw together with the page instead of after a separate download.
*/
@font-face {
  font-family: "remixicon";
  src: url("data:font/woff2;base64,${font.toString('base64')}") format("woff2");
  font-display: block;
}
[class^="ri-"], [class*=" ri-"] {
  font-family: 'remixicon' !important;
  font-style: normal;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}
${names.map(n => `.${n}:before { content: "\\${glyphs.get(n).toString(16)}"; }`).join('\n')}
`;

const outPath = path.join(ROOT, OUT);
const before = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
fs.writeFileSync(outPath, css);
const hash = crypto.createHash('sha256').update(css).digest('hex').slice(0, 8);
for (const rel of REFERENCES) {
  const file = path.join(ROOT, rel);
  const text = fs.readFileSync(file, 'utf8');
  // Only quoted URLs (href="..." and the sw.js list), not mentions in comments.
  const next = text.replace(/css\/remixicon\.css(\?v=[0-9a-z.-]+)?(?=["'])/g, `css/remixicon.css?v=${hash}`);
  if (!next.includes(`css/remixicon.css?v=${hash}`)) throw new Error(`${rel} does not link ${OUT}`);
  if (next !== text) fs.writeFileSync(file, next);
}

console.log(`${OUT}: ${names.length} icons, font ${(font.length / 1024).toFixed(1)} KB, stylesheet ${(css.length / 1024).toFixed(1)} KB, ?v=${hash}`);
if (unknown.size) console.log('Not Remix Icon glyphs, ignored:', [...unknown].sort().join(' '));
console.log(css === before ? 'No change.' : 'Changed: bump CACHE_NAME in sw.js.');
